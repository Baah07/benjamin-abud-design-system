import { test } from 'node:test';
import assert from 'node:assert/strict';
import { componentPage, componentsIndex, figmaUrl } from '../scripts/lib/pages.mjs';

const cfg = { fileKey: 'ABC123', repoUrl: 'https://github.com/owner/repo' };
const button = {
  slug: 'button', name: 'Button', level: 'atom', id: '246:420', variants: 24, related: ['Segmented'],
  description: 'C01 Button.',
  props: [['Label', 'TEXT', 'Continuar'], ['Variant', 'VARIANT', ['Primary', 'Secondary']], ['Leading icon', 'INSTANCE_SWAP', null]],
};

test('figmaUrl uses dashes in node-id', () => {
  assert.equal(figmaUrl('ABC123', '246:420'), 'https://www.figma.com/design/ABC123/?node-id=246-420');
});

test('component page has generated header, Figma link, description and props table', () => {
  const md = componentPage(button, cfg);
  assert.match(md, /^<!-- Generated by scripts\/build-pages\.mjs/);
  assert.match(md, /^# Button$/m);
  assert.match(md, /\*\*Level:\*\* Atom/);
  assert.match(md, /\(https:\/\/www\.figma\.com\/design\/ABC123\/\?node-id=246-420\)/);
  assert.match(md, /C01 Button\./);
  assert.match(md, /\| Variant \| Variant \| `Primary` · `Secondary` \|/);
  assert.match(md, /\| Label \| Text \| `Continuar` \|/);
  assert.match(md, /\| Leading icon \| Instance swap \| — \|/);
});

test('missing description is shown as an explicit TODO, never invented', () => {
  assert.match(componentPage({ ...button, description: '' }, cfg), /> TODO: no description in Figma yet\./);
});

test('index groups components by atomic level with relative links', () => {
  const md = componentsIndex([button, { ...button, slug: 'card', name: 'Card', level: 'molecule' }], cfg);
  assert.ok(md.indexOf('## Atoms') < md.indexOf('## Molecules'));
  assert.match(md, /\[Button\]\(components\/button\.md\)/);
});
