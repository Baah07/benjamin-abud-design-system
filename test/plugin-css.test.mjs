import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parsePluginCss } from '../scripts/lib/plugin-css.mjs';

const css = `/* Generated by Token Exporter */

/* Semantic Tokens (Light) */
:root {
  --Semantic-Tokens-bg-fill-primary: #4038db;
}

/* Semantic Tokens (Dark) */
[data-theme="Dark"] {
  --Semantic-Tokens-bg-fill-primary: #2119b4;
}

/* Dimension */
:root {
  --Dimension-radius-md: 8px;
}`;

test('parsePluginCss returns token path, mode and value per declaration', () => {
  assert.deepEqual(parsePluginCss(css), [
    { path: 'bg-fill-primary', mode: null, value: '#4038db' },
    { path: 'bg-fill-primary', mode: 'Dark', value: '#2119b4' },
    { path: 'radius-md', mode: null, value: '8px' },
  ]);
});
