import { test } from 'node:test';
import assert from 'node:assert/strict';
import { replaceBlock, splitSections, tierOf, figmaToPath, toYaml, componentPage, figmaUrl } from '../scripts/lib/docs.mjs';

test('replaceBlock fills an HTML marker block and keeps the markers', () => {
  const src = 'a\n<!-- DESIGN:links:start -->\nold\n<!-- DESIGN:links:end -->\nb';
  assert.equal(replaceBlock(src, 'DESIGN:links', 'new'), 'a\n<!-- DESIGN:links:start -->\nnew\n<!-- DESIGN:links:end -->\nb');
});

test('replaceBlock fills a YAML comment marker block', () => {
  const src = '---\n# DESIGN:rounded:start\nx: 1\n# DESIGN:rounded:end\n---';
  assert.equal(replaceBlock(src, 'DESIGN:rounded', 'rounded:\n  sm: 4px'), '---\n# DESIGN:rounded:start\nrounded:\n  sm: 4px\n# DESIGN:rounded:end\n---');
});

test('replaceBlock throws when the marker is missing so a typo never ships silently', () => {
  assert.throws(() => replaceBlock('nothing', 'DESIGN:nope', 'x'), /DESIGN:nope/);
});

test('splitSections returns every ## section body, without the front matter', () => {
  const md = '---\na: 1\n---\n# T\nintro\n## Uno\nuno\n### sub\nmás\n## Dos\ndos\n';
  const s = splitSections(md);
  assert.deepEqual(Object.keys(s), ['Uno', 'Dos']);
  assert.equal(s.Uno.trim(), 'uno\n### sub\nmás');
});

test('tierOf classifies token paths by tier', () => {
  assert.equal(tierOf('color.palette.indigo.600'), 'Primitivo');
  assert.equal(tierOf('bg.fill.primary'), 'Semántico');
  assert.equal(tierOf('style.bg.paper'), 'Estilo');
  assert.equal(tierOf('space.4'), 'Dimensión');
  assert.equal(tierOf('typography.body.md'), 'Estilo de texto');
  assert.equal(tierOf('layout.grid.margin'), 'Layout');
});

test('figmaToPath converts Figma variable and style names to token paths', () => {
  assert.equal(figmaToPath('bg/fill/primary'), 'bg.fill.primary');
  assert.equal(figmaToPath('typography/body/md'), 'typography.body.md');
});

test('toYaml emits nested maps, lists and quoted strings', () => {
  assert.equal(toYaml({ a: 1, b: 'x: y', c: [{ d: true }], e: {} }), 'a: 1\nb: "x: y"\nc:\n  - d: true\ne: {}');
});

test('figmaUrl uses dashes in node-id', () => {
  assert.equal(figmaUrl('K', '246:420'), 'https://www.figma.com/design/K/?node-id=246-420');
});

const ctx = {
  fileKey: 'K', repo: 'o/r',
  lookup: (p) => (p === 'bg.fill.primary' ? { tier: 'Semántico', value: 'oklch(1% 0 0)', dark: 'oklch(2% 0 0)', description: 'Primary.' } : null),
};
const button = {
  slug: 'button', name: 'Button', level: 'atom', id: '246:420', variants: 24, related: ['Segmented'],
  description: 'C01 Button. Label y Variant conservados.', defaultVariant: 'Variant=Primary, State=Default',
  props: [['Label', 'TEXT', 'Continuar'], ['Variant', 'VARIANT', ['Primary', 'Secondary']], ['State', 'VARIANT', ['Default', 'Hover']]],
  variables: ['bg/fill/primary', 'button'], textStyles: ['typography/body/button-md'], effectStyles: [],
};

test('component page follows the section template in order', () => {
  const md = componentPage(button, ctx);
  const order = ['# Button', '## Cómo usarlo', '## Props', '## Variantes', '## Estados', '## Descripción en Figma', '## Partes relacionadas', '## Tokens', '## Vista previa', '## Fuente'];
  const idx = order.map((h) => md.indexOf(`\n${h}\n`));
  assert.ok(idx.every((i) => i > 0), JSON.stringify(idx));
  assert.deepEqual([...idx].sort((a, b) => a - b), idx);
  assert.match(md, /^<!-- Generated by scripts\/build-docs\.mjs/);
  assert.match(md, /^> C01 Button\.$/m);
});

test('props table uses Figma defaults', () => {
  const md = componentPage(button, ctx);
  assert.match(md, /\| `Variant` \| Variante \| `Primary`, `Secondary` \| `Primary` \|/);
  assert.match(md, /\| `Label` \| Texto \| Cualquier texto \| `Continuar` \|/);
});

test('tokens table resolves known tokens and lists variables outside the system', () => {
  const md = componentPage(button, ctx);
  assert.match(md, /\| `--bg-fill-primary` \| Semántico \| `oklch\(1% 0 0\)` \| `oklch\(2% 0 0\)` \| Primary\. \|/);
  assert.match(md, /### Variables fuera del sistema\n\n- `button`/);
});

test('usage line separates level, variants and Figma with spaced dots', () => {
  assert.match(componentPage(button, ctx), /\*\*Nivel:\*\* Átomo · \*\*Variantes:\*\* 24 · \*\*Figma:\*\*/);
});

test('states come from the State variant property', () => {
  assert.match(componentPage(button, ctx), /Estados diseñados en Figma: `Default`, `Hover`\./);
});
