// tokens.json → tokens.css (CSS Color 4 custom properties), tokens.js, tokens.d.ts via Style Dictionary.
import { readFile, writeFile } from 'node:fs/promises';
import StyleDictionary from 'style-dictionary';
import { toOklch, toLegacy } from './lib/color.mjs';
import { flatten, unflatten, resolve } from './lib/dtcg.mjs';

const root = new URL('../', import.meta.url);
const tokens = JSON.parse(await readFile(new URL('tokens.json', root), 'utf8'));
const { $description, darkTheme, lienzoStyle, tabletViewport, desktopViewport, ...baseTree } = tokens;
const base = flatten(baseTree);

const dim = (v) => `${v.value}${v.unit}`;
const family = (f) => (Array.isArray(f) ? f : [f]).map((n) => (/\s/.test(n) ? `"${n}"` : n)).concat('sans-serif').join(', ');
function cssValue(token, color = toOklch) {
  const v = token.$value;
  switch (token.$type) {
    case 'color': return color(v);
    case 'dimension': return dim(v);
    case 'fontFamily': return family(v);
    case 'typography': return `${v.fontWeight} ${dim(v.fontSize)}/${v.lineHeight} ${family(v.fontFamily)}`;
    case 'shadow': return (Array.isArray(v) ? v : [v]).map((l) => `${dim(l.offsetX)} ${dim(l.offsetY)} ${dim(l.blur)} ${dim(l.spread)} ${color(l.color)}`).join(', ');
    default: return v;
  }
}

// Two Style Dictionary platforms over the same tokens: CSS Color 4 (oklch) and a legacy one (hex / rgba)
// that only carries literal colors and shadows, emitted inside @supports not (color: oklch(…)).
const hooks = {
  transforms: {
    'ba/css-value': { type: 'value', transitive: true, filter: (t) => typeof t.$value === 'object', transform: (t) => cssValue(t) },
    'ba/css-legacy': { type: 'value', transitive: true, filter: (t) => typeof t.$value === 'object', transform: (t) => cssValue(t, toLegacy) },
  },
};
const PLATFORMS = { css: ['name/kebab', 'ba/css-value'], legacy: ['name/kebab', 'ba/css-legacy'] };
const isLiteralColor = (t) => ['color', 'shadow'].includes(t.$type) && typeof t.original.$value === 'object';

// Renders the declarations for `paths` from the full tree `flat`, keeping aliases as var() references.
async function declarations(flat, paths, platform = 'css') {
  const keep = platform === 'legacy' ? (t) => paths.has(t.path.join('.')) && isLiteralColor(t) : (t) => paths.has(t.path.join('.'));
  const sd = new StyleDictionary({
    tokens: unflatten(flat),
    hooks,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      [platform]: {
        transforms: PLATFORMS[platform],
        files: [{ destination: 'x.css', format: 'css/variables', filter: keep, options: { outputReferences: true, showFileHeader: false, selector: ':root' } }],
      },
    },
  });
  const [file] = await sd.formatPlatform(platform);
  // A layer can have nothing to emit (e.g. Lienzo overrides are all aliases, which inherit the legacy primitives).
  return (file?.output ?? '').replace(/^:root \{\n/, '').replace(/\n?\}\n?$/, '').trimEnd();
}

const all = new Set(Object.keys(base));
const layer = async (tree, platform) => {
  const flat = flatten(tree);
  return declarations({ ...base, ...flat }, new Set(Object.keys(flat)), platform);
};
const minWidth = (tree) => {
  const merged = resolve(unflatten({ ...base, ...flatten(tree) }));
  return dim(merged['layout.breakpoint.min-width'].$value);
};
const indent = (s) => s.split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');
const css = [
  [
    '/**',
    ' * Benjamín Abud design tokens — generated by scripts/build-tokens.mjs from tokens.json (DTCG 2025.10).',
    ' * Colors use CSS Color 4 oklch(); browsers without it get hex/rgba from the @supports not block at the end.',
    ' * Do not edit by hand.',
    ' * Theme: <html data-theme="light|dark"> (defaults to prefers-color-scheme). Style: <html data-style="lienzo">.',
    ' */',
  ].join('\n'),
  `:root {\n${await declarations(base, all)}\n}`,
  `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${indent(await layer(darkTheme))}\n  }\n}`,
  `:root[data-theme="dark"] {\n${await layer(darkTheme)}\n}`,
  `:root[data-style="lienzo"] {\n${await layer(lienzoStyle)}\n}`,
  `@media (min-width: ${minWidth(tabletViewport)}) {\n  :root {\n${indent(await layer(tabletViewport))}\n  }\n}`,
  `@media (min-width: ${minWidth(desktopViewport)}) {\n  :root {\n${indent(await layer(desktopViewport))}\n  }\n}`,
  // Same selectors and order as above, so the cascade resolves exactly like the oklch blocks.
  `@supports not (color: oklch(0% 0 0)) {\n${indent([
    [':root', await declarations(base, all, 'legacy')],
    ['@media (prefers-color-scheme: dark) { :root:not([data-theme="light"])', await layer(darkTheme, 'legacy')],
    [':root[data-theme="dark"]', await layer(darkTheme, 'legacy')],
    [':root[data-style="lienzo"]', await layer(lienzoStyle, 'legacy')],
  ].filter(([, body]) => body).map(([selector, body]) => (selector.startsWith('@media')
    ? `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${indent(body)}\n  }\n}`
    : `${selector} {\n${body}\n}`)).join('\n\n'))}\n}`,
  '',
].join('\n\n');
await writeFile(new URL('tokens.css', root), css);

// JS/TS exports: resolved CSS values for every theme/style/viewport combination's base, plus overrides per group.
const resolvedCss = (tree) => Object.fromEntries(Object.entries(resolve(tree)).map(([k, t]) => [k, cssValue(t)]));
const groups = { darkTheme, lienzoStyle, tabletViewport, desktopViewport };
const js = {
  base: resolvedCss(baseTree),
  ...Object.fromEntries(Object.entries(groups).map(([g, tree]) => {
    const merged = resolvedCss(unflatten({ ...base, ...flatten(tree) }));
    const changed = Object.fromEntries(Object.entries(merged).filter(([k, v]) => v !== resolvedCss(baseTree)[k]));
    return [g, changed];
  })),
};
const names = Object.keys(js.base).map((k) => JSON.stringify(k)).join(' | ');
await writeFile(new URL('tokens.js', root), `// Generated by scripts/build-tokens.mjs. Resolved CSS values keyed by token path.\nexport const tokens = ${JSON.stringify(js, null, 2)};\nexport default tokens;\n`);
await writeFile(new URL('tokens.d.ts', root), `// Generated by scripts/build-tokens.mjs.\nexport type TokenPath = ${names};\nexport type TokenMap = Partial<Record<TokenPath, string | number>>;\nexport declare const tokens: { base: Record<TokenPath, string | number>; darkTheme: TokenMap; lienzoStyle: TokenMap; tabletViewport: TokenMap; desktopViewport: TokenMap };\nexport default tokens;\n`);
console.log(`tokens.css (${css.length} bytes), tokens.js, tokens.d.ts`);
