// Helpers shared by scripts/build-docs.mjs: marker blocks, DESIGN.md sections, token tiers, YAML, component pages.

export const SYSTEM = 'Design System de Benjamín Abud';
export const GEN = (sources) => `<!-- Generated by scripts/build-docs.mjs from ${sources}. Do not edit. -->`;
export const LEVELS = [['atom', 'Átomos'], ['molecule', 'Moléculas'], ['organism', 'Organismos']];
export const LEVEL_ONE = { atom: 'Átomo', molecule: 'Molécula', organism: 'Organismo' };
export const figmaUrl = (fileKey, nodeId) => `https://www.figma.com/design/${fileKey}/?node-id=${nodeId.replace(':', '-')}`;
export const cssVar = (path) => `--${path.replace(/\./g, '-')}`;
export const figmaToPath = (name) => name.replace(/\//g, '.');
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => `\`${esc(s)}\``;

// Fills <!-- NAME:start -->…<!-- NAME:end --> or "# NAME:start" … "# NAME:end" (YAML front matter).
export function replaceBlock(src, name, body) {
  const html = new RegExp(`(<!-- ${name}:start -->\\n)[\\s\\S]*?(<!-- ${name}:end -->)`);
  const yaml = new RegExp(`(# ${name}:start\\n)[\\s\\S]*?(# ${name}:end)`);
  const re = html.test(src) ? html : yaml.test(src) ? yaml : null;
  if (!re) throw new Error(`Marker ${name} not found`);
  return src.replace(re, (_, start, end) => `${start}${body.trim()}\n${end}`);
}

export function splitSections(md) {
  const body = md.replace(/^---\n[\s\S]*?\n---\n/, '');
  const out = {};
  let current = null;
  for (const line of body.split('\n')) {
    const h = line.match(/^## (.+)$/);
    if (h) { current = h[1].trim(); out[current] = ''; continue; }
    if (current) out[current] += `${line}\n`;
  }
  return out;
}

export function tierOf(path) {
  const head = path.split('.')[0];
  if (path.startsWith('color.palette.')) return 'Primitivo';
  if (['bg', 'text', 'border'].includes(head)) return 'Semántico';
  if (head === 'style') return 'Estilo';
  if (['size', 'space', 'radius', 'count'].includes(head)) return 'Dimensión';
  if (head === 'typography') return 'Estilo de texto';
  if (head === 'font') return 'Tipografía';
  if (head === 'layout') return 'Layout';
  if (head === 'elevation') return 'Elevación';
  return 'Otro';
}

const scalar = (v) => {
  if (typeof v === 'number' || typeof v === 'boolean' || v === null) return String(v);
  const s = String(v);
  return /^[\w./@+-][\w ./@+-]*$/.test(s) && !/^(true|false|null|\d[\d.]*)$/.test(s) && !/ $/.test(s) ? s : JSON.stringify(s);
};
export function toYaml(value, indent = 0) {
  const pad = ' '.repeat(indent);
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return value.map((item) => {
      if (item && typeof item === 'object') {
        const inner = toYaml(item, indent + 2).split('\n');
        return `${pad}- ${inner[0].trimStart()}${inner.length > 1 ? `\n${inner.slice(1).join('\n')}` : ''}`;
      }
      return `${pad}- ${scalar(item)}`;
    }).join('\n');
  }
  if (value && typeof value === 'object') {
    return Object.entries(value).map(([k, v]) => {
      const key = /^[\w.-]+$/.test(k) ? k : JSON.stringify(k);
      if (v && typeof v === 'object' && Object.keys(v).length) return `${pad}${key}:\n${toYaml(v, indent + 2)}`;
      if (v && typeof v === 'object') return `${pad}${key}: ${Array.isArray(v) ? '[]' : '{}'}`;
      return `${pad}${key}: ${scalar(v)}`;
    }).join('\n');
  }
  return `${pad}${scalar(value)}`;
}

const TYPE = { TEXT: 'Texto', BOOLEAN: 'Booleano', VARIANT: 'Variante', INSTANCE_SWAP: 'Instancia', SLOT: 'Slot' };
const parseDefault = (def) => Object.fromEntries((def ?? '').split(', ').filter(Boolean).map((kv) => kv.split('=')));
export const summary = (c) => (c.description ? `${c.description.split(/(?<=\.)\s/)[0]}` : 'TODO: sin descripción en Figma.');

function allowed(type, value) {
  if (type === 'VARIANT') return value.map(code).join(', ');
  if (type === 'TEXT') return 'Cualquier texto';
  if (type === 'BOOLEAN') return '`true`, `false`';
  if (type === 'INSTANCE_SWAP') return 'Una instancia de icono';
  return 'Instancias de componentes';
}

// ctx: { fileKey, repo, lookup(path) → { tier, value, dark?, lienzo?, description } | null }
export function componentPage(c, ctx) {
  const raw = (p) => `https://raw.githubusercontent.com/${ctx.repo}/main/${p}`;
  const defs = parseDefault(c.defaultVariant);
  const variantProps = c.props.filter(([, t]) => t === 'VARIANT');
  const state = variantProps.find(([n]) => n === 'State');
  const L = [
    GEN('figma/components.json, tokens.json and the Figma file'), '',
    `# ${c.name}`, '',
    `> ${summary(c)}`, '',
    `Parte del [${SYSTEM}](../README.md). Es un componente de Figma: sus props son las propiedades del componente en Figma y sus estilos salen solo de tokens. Los tokens se linkean como muestra [Primeros pasos](../foundations/getting-started.md). Todos los componentes: [Componentes](../COMPONENTS.md).`, '',
    '## Cómo usarlo', '',
    `**Nivel:** ${LEVEL_ONE[c.level]} · **Variantes:** ${c.variants} · **Figma:** [abrir el componente](${figmaUrl(ctx.fileKey, c.id)})`, '',
    c.defaultVariant ? `**Variante por defecto:** ${Object.entries(defs).map(([k, v]) => `${k} = ${code(v)}`).join(', ')}` : '**Variante por defecto:** el componente no tiene variantes.', '',
  ];
  if (c.props.length) {
    L.push('## Props', '', '| Prop | Tipo | Valores permitidos | Default | Descripción |', '|---|---|---|---|---|');
    for (const [name, type, value] of c.props) {
      const def = type === 'VARIANT' ? (defs[name] !== undefined ? code(defs[name]) : '—') : value === null || value === undefined ? '—' : code(value);
      L.push(`| ${code(name)} | ${TYPE[type] ?? type} | ${allowed(type, value)} | ${def} | — |`);
    }
    L.push('');
  }
  if (variantProps.length) {
    L.push('## Variantes', '', `Variantes disponibles: ${c.variants}, combinando ${variantProps.map(([n]) => code(n)).join(', ')}.`, '');
    for (const [name, , values] of variantProps.filter(([n]) => n !== 'State')) L.push(`- **${name}:** ${values.map(code).join(', ')}`);
    L.push('');
  }
  if (state) L.push('## Estados', '', `Estados diseñados en Figma: ${state[2].map(code).join(', ')}.`, '');
  L.push('## Descripción en Figma', '', c.description ? c.description.split(/(?<=\.)\s+/).map((s) => `- ${s}`).join('\n') : '> TODO: el componente no tiene descripción en Figma.', '');
  if (c.related?.length) L.push('## Partes relacionadas', '', 'Otros componentes en la misma página de Figma:', '', ...c.related.map((r) => `- ${r}`), '');

  const known = [];
  const outside = [];
  for (const name of [...(c.variables ?? []), ...(c.textStyles ?? []), ...(c.effectStyles ?? [])]) {
    const path = figmaToPath(name);
    const t = ctx.lookup(path);
    if (t) known.push([path, t]); else outside.push(name);
  }
  L.push('## Tokens', '', 'Todo lo que el componente tiene enlazado en Figma: variables, estilos de texto y de efecto. Valores en claro; la columna Oscuro y la nota Lienzo solo aparecen cuando el valor cambia.', '');
  if (known.length) {
    L.push('| Token | Nivel | Valor | Oscuro | Para qué es |', '|---|---|---|---|---|');
    for (const [path, t] of known) {
      const value = t.lienzo ? `${code(t.value)} (Lienzo: ${code(t.lienzo)})` : code(t.value);
      L.push(`| ${code(cssVar(path))} | ${t.tier} | ${value} | ${t.dark ? code(t.dark) : '—'} | ${esc(t.description || '—')} |`);
    }
    L.push('');
  }
  if (outside.length) L.push('### Variables fuera del sistema', '', ...outside.map((n) => `- ${code(n)}`), '', 'Estas variables están enlazadas en Figma pero no pertenecen a ninguna colección exportada. Hay que reemplazarlas por tokens del sistema.', '');
  L.push('## Vista previa', '', `![${c.name} en Figma](../assets/components/${c.slug}.png)`, '');
  L.push('## Fuente', '',
    `- El sistema entero como un documento Design System Doc Spec: [benjamin-abud-design-system.dsds.yaml](${raw('benjamin-abud-design-system.dsds.yaml')}), donde este componente es la entrada \`${c.slug}\``,
    `- Los componentes como datos: [components-api.json](${raw('components-api.json')})`,
    `- El inventario exportado de Figma: [figma/components.json](${raw('figma/components.json')})`,
    `- Los tokens: [tokens.json](${raw('tokens.json')})`,
    `- El nodo en Figma: [${c.name}](${figmaUrl(ctx.fileKey, c.id)})`, '');
  return L.join('\n');
}
