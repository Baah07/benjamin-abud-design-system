// Markdown generators for components/*.md and COMPONENTS.md.

export const HEADER = '<!-- Generated by scripts/build-pages.mjs from figma/components.json. Do not edit by hand: change Figma, re-export, run `npm run build`. -->';
export const LEVELS = [['atom', 'Atoms'], ['molecule', 'Molecules'], ['organism', 'Organisms']];

const TYPE_LABEL = { TEXT: 'Text', BOOLEAN: 'Boolean', VARIANT: 'Variant', INSTANCE_SWAP: 'Instance swap', SLOT: 'Slot' };
const levelLabel = (level) => level[0].toUpperCase() + level.slice(1);
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

export const figmaUrl = (fileKey, nodeId) => `https://www.figma.com/design/${fileKey}/?node-id=${nodeId.replace(':', '-')}`;

function propValue(type, value) {
  if (type === 'VARIANT') return value.map((v) => `\`${cell(v)}\``).join(' · ');
  if (value === null || value === undefined) return '—';
  return `\`${cell(value)}\``;
}

export function componentPage(c, { fileKey }) {
  const lines = [
    HEADER, '',
    `# ${c.name}`, '',
    `**Level:** ${levelLabel(c.level)} · **Variants:** ${c.variants} · **Figma:** [open component](${figmaUrl(fileKey, c.id)})`, '',
    '## Description', '',
    c.description ? cell(c.description) : '> TODO: no description in Figma yet.', '',
  ];
  if (c.props.length) {
    lines.push('## Properties', '', '| Property | Type | Values / default |', '| --- | --- | --- |');
    for (const [name, type, value] of c.props) lines.push(`| ${cell(name)} | ${TYPE_LABEL[type] ?? type} | ${propValue(type, value)} |`);
    lines.push('');
  }
  if (c.related?.length) lines.push('## Related parts on the same Figma page', '', ...c.related.map((r) => `- ${r}`), '');
  lines.push('## Tokens', '', 'Styled only with tokens from [`tokens.css`](../tokens.css). See [foundations](../foundations/README.md).', '');
  lines.push('## Preview', '', `![${c.name}](../assets/components/${c.slug}.png)`, '');
  return lines.join('\n');
}

export function componentsIndex(components) {
  const lines = [HEADER.replace('figma/components.json', 'figma/components.json (index)'), '', '# Components', ''];
  for (const [level, title] of LEVELS) {
    const items = components.filter((c) => c.level === level);
    if (!items.length) continue;
    lines.push(`## ${title}`, '', '| Component | Variants | Summary |', '| --- | --- | --- |');
    for (const c of items) lines.push(`| [${c.name}](components/${c.slug}.md) | ${c.variants} | ${cell((c.description || 'TODO').split('. ')[0])} |`);
    lines.push('');
  }
  return lines.join('\n');
}
