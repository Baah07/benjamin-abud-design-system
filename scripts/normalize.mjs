// figma/tokens.figma.json (Token Exporter) + figma/patches.json + figma/styles.json
//   → tokens.json (base + override groups) and tokens.resolver.json (DTCG Resolver Module 2025.10).
import { readFile, writeFile } from 'node:fs/promises';
import Color from 'colorjs.io';
import { applyPatches, splitModes, stripModeFromAliases, retypeFromAliases, applyRetype } from './lib/normalize.mjs';
import { flatten, unflatten, isToken, validate } from './lib/dtcg.mjs';

const read = async (p) => JSON.parse(await readFile(new URL(`../${p}`, import.meta.url), 'utf8'));
const write = (p, data) => writeFile(new URL(`../${p}`, import.meta.url), `${JSON.stringify(data, null, 2)}\n`);

const MODES = {
  'Primitives-colors': ['Light', 'Dark'],
  'Semantic-Tokens': ['Light', 'Dark'],
  Layout: ['Mobile', 'Tablet', 'Desktop'],
  Dimension: [],
  'Typography-Tokens': [],
  Style: ['Clásico', 'Lienzo'],
};

// Base = light theme, Clásico style, Mobile viewport (mobile-first CSS). Each group overrides the base.
export const GROUPS = {
  darkTheme: { 'Primitives-colors': 'Dark', 'Semantic-Tokens': 'Dark' },
  lienzoStyle: { Style: 'Lienzo' },
  tabletViewport: { Layout: 'Tablet' },
  desktopViewport: { Layout: 'Desktop' },
};
const BASE = { 'Primitives-colors': 'Light', 'Semantic-Tokens': 'Light', Layout: 'Mobile', Style: 'Clásico' };

const r = (n, d = 4) => Number(n.toFixed(d));
function toOklchValue(v) {
  if (!v || typeof v !== 'object' || !Array.isArray(v.components)) return v;
  const c = new Color(v.colorSpace, v.components, v.alpha ?? 1);
  const [l, ch, h] = c.to('oklch').coords;
  const chroma = r(ch);
  return { colorSpace: 'oklch', components: [r(l), chroma, chroma === 0 || Number.isNaN(h) ? 0 : r(h, 2)], alpha: r(v.alpha ?? 1, 3), hex: c.to('srgb').toString({ format: 'hex', collapse: false }) };
}
const convertColors = (flat) => Object.fromEntries(Object.entries(flat).map(([k, t]) => {
  if (t.$type === 'color') return [k, { ...t, $value: toOklchValue(t.$value) }];
  if (t.$type === 'shadow') return [k, { ...t, $value: t.$value.map((l) => ({ ...l, color: toOklchValue(l.color) })) }];
  return [k, t];
}));

const patches = await read('figma/patches.json');
const exported = applyPatches(await read('figma/tokens.figma.json'), patches);
const { $description: _, ...styles } = await read('figma/styles.json');
const split = splitModes(exported, MODES);

const pick = (selection) => {
  const flat = {};
  for (const collection of Object.keys(MODES)) {
    const mode = selection[collection] ?? 'default';
    Object.assign(flat, flatten(stripModeFromAliases(split[collection][mode], MODES)));
  }
  Object.assign(flat, flatten(styles));
  return retypeFromAliases(applyRetype(flat, patches.$retype));
};

const base = pick(BASE);
const baseFlat = convertColors(base.tokens);
const overrides = {};
for (const [group, selection] of Object.entries(GROUPS)) {
  const flat = convertColors(pick({ ...BASE, ...selection }).tokens);
  const diff = Object.fromEntries(Object.entries(flat).filter(([k, t]) => JSON.stringify(t.$value) !== JSON.stringify(baseFlat[k].$value)));
  overrides[group] = unflatten(diff);
}

const tokens = {
  $description: 'Benjamín Abud design tokens in DTCG 2025.10. Source: Figma file FvaEDyROUUsM8ntHj8C9f8, exported with the Token Exporter plugin (variables) plus figma/styles.json (text and effect styles). Tiers: color.palette.* primitives feed semantic roles (bg, text, border) and the Style collection (style.*). The base is light theme + Clásico style + Mobile viewport; darkTheme, lienzoStyle, tabletViewport and desktopViewport override it. Generated by scripts/normalize.mjs — do not edit by hand.',
  ...unflatten(baseFlat),
  ...overrides,
};

const errors = validate(unflatten(baseFlat));
for (const [group, tree] of Object.entries(overrides)) {
  const merged = { ...baseFlat, ...flatten(tree) };
  errors.push(...validate(unflatten(merged)).map((e) => `${group}: ${e}`));
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const ctx = (group) => [{ $ref: `tokens.json#/${group}` }];
const resolver = {
  $schema: 'https://www.designtokens.org/schemas/2025.10/resolver.json',
  name: 'Benjamín Abud design system',
  version: '2025.10',
  description: 'How themes, styles and viewports combine. The base set is tokens.json with the override groups emptied out. scripts/build-tokens.mjs emits the same combinations as CSS: base at :root, dark under prefers-color-scheme and [data-theme=dark], Lienzo under [data-style=lienzo], tablet and desktop under min-width media queries (layout.breakpoint.min-width).',
  sets: { base: { description: 'Light theme, Clásico style, Mobile viewport.', sources: [{ $ref: 'tokens.json', ...Object.fromEntries(Object.keys(GROUPS).map((g) => [g, {}])) }] } },
  modifiers: {
    theme: { description: 'Figma modes Light / Dark (Primitives colors + Semantic Tokens).', contexts: { light: [], dark: ctx('darkTheme') }, default: 'light' },
    style: { description: 'Figma Style collection modes Clásico / Lienzo.', contexts: { clasico: [], lienzo: ctx('lienzoStyle') }, default: 'clasico' },
    viewport: { description: 'Figma Layout modes Mobile / Tablet / Desktop.', contexts: { mobile: [], tablet: ctx('tabletViewport'), desktop: ctx('desktopViewport') }, default: 'mobile' },
  },
  resolutionOrder: [{ $ref: '#/sets/base' }, { $ref: '#/modifiers/theme' }, { $ref: '#/modifiers/style' }, { $ref: '#/modifiers/viewport' }],
};

await write('tokens.json', tokens);
await write('tokens.resolver.json', resolver);
const count = Object.keys(baseFlat).length;
console.log(`tokens.json: ${count} base tokens; overrides ${Object.entries(overrides).map(([g, t]) => `${g}=${Object.keys(flatten(t)).length}`).join(', ')}`);
if (base.changes.length) console.log(`retyped from alias targets: ${base.changes.map((c) => `${c.path} ${c.from}→${c.to}`).join(', ')}`);
